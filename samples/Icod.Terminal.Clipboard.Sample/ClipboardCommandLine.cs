using System.Text;

namespace Icod.Terminal.Clipboard.Sample;
using System.Globalization;
using System.Text;

internal static class ClipboardCommandLine {
	internal const string HelpText = """
Usage: Icod.Terminal.Clipboard.Sample [operation] [limits]
  --help                         Show help without opening a terminal.
  --write TEXT                   Explicitly replace the clipboard (empty clears it).
  --generated-bytes N             Write N generated ASCII bytes (0..16777216).
  --read                         Explicitly read the clipboard; report byte count only.
  --maximum-read-bytes N          Local read limit, default 65536; range 1..16777216.
  --maximum-write-bytes N         Local write limit, default 65536; range 1..16777216.
A positional TEXT argument is also an explicit write. Combine a write with --read
for a generated/text round-trip check. Writes overwrite existing clipboard contents.
Limits authorize local resources; they do not negotiate terminal capacity.
""";

	internal static async Task<int> RunAsync(
		string[] args, TextWriter output, TextWriter error,
		Func<TerminalSessionOptions, CancellationToken, ValueTask<TerminalSession>> open,
		CancellationToken cancellationToken = default
	) {
		if ( args.Length == 0 || args.SequenceEqual( new[] { "--help" } ) ) {
			await output.WriteLineAsync( HelpText );
			return 0;
		}
		string? text = null;
		int? generated = null;
		bool read = false;
		int maximumRead = TerminalClipboardOptions.DefaultMaximumBytes;
		int maximumWrite = TerminalClipboardOptions.DefaultMaximumBytes;
		byte[]? expected = null;
		try {
			for ( int i = 0; i < args.Length; ++i ) {
				switch ( args[ i ] ) {
					case "--read": read = true; break;
					case "--write": text = Next( args, ref i ); break;
					case "--generated-bytes": generated = Number( Next( args, ref i ), 0 ); break;
					case "--maximum-read-bytes": maximumRead = Number( Next( args, ref i ), 1 ); break;
					case "--maximum-write-bytes": maximumWrite = Number( Next( args, ref i ), 1 ); break;
					default:
						if ( args.Length == 1 && !args[ i ].StartsWith( "--", StringComparison.Ordinal ) ) text = args[ i ];
						else throw new ArgumentException( "Unknown or incomplete clipboard command." );
						break;
				}
			}
			if ( text is not null && generated.HasValue )
				throw new ArgumentException( "Choose either text or generated bytes for the write." );
			if ( text is null && !generated.HasValue && !read )
				throw new ArgumentException( "Choose an explicit read or write operation." );
			int count = generated ?? ( text is null ? 0 : new UTF8Encoding( false, true ).GetByteCount( text ) );
			if ( count > maximumWrite )
				throw new ArgumentException( "The write exceeds the local write-byte limit; raise --maximum-write-bytes explicitly." );
			if ( text is not null ) expected = new UTF8Encoding( false, true ).GetBytes( text );
			else if ( generated.HasValue ) {
				expected = new byte[ count ];
				for ( int i = 0; i < count; ++i ) expected[ i ] = (byte)( 'A' + i % 26 );
			}
		} catch ( ArgumentException ) {
			await error.WriteLineAsync( "Invalid clipboard command, text, or byte limit. Check --help; writes must fit the local write-byte limit." );
			return 2;
		}
		try {
			await using TerminalSession session = await open( new TerminalSessionOptions {
				InputMode = TerminalInputMode.CBreak,
				EchoInput = false,
				ClipboardOptions = new() { MaximumReadBytes = maximumRead, MaximumWriteBytes = maximumWrite }
			}, cancellationToken );
			if ( expected is not null ) {
				await session.WriteClipboardAsync( TerminalClipboardSelection.Clipboard, expected, cancellationToken );
				await output.WriteLineAsync( $"Emitted an OSC 52 write of {expected.Length} decoded bytes; terminal acceptance is unconfirmed." );
			}
			if ( read ) {
				byte[] actual = await session.ReadClipboardAsync( TerminalClipboardSelection.Clipboard,
					TimeSpan.FromSeconds( 5 ), cancellationToken );
				await output.WriteLineAsync( $"Received {actual.Length} decoded clipboard bytes." );
				if ( expected is not null ) {
					bool matches = expected.AsSpan().SequenceEqual( actual );
					await output.WriteLineAsync( matches ? "The explicit round trip matched." : "The explicit round trip did not match." );
					if ( !matches ) return 1;
				}
			}
			return 0;
		} catch ( TimeoutException ) {
			await error.WriteLineAsync( "No reply arrived before the deadline. Clipboard policy or capacity remains unknown." );
			return 1;
		} catch ( OperationCanceledException ) when ( cancellationToken.IsCancellationRequested ) {
			await error.WriteLineAsync( "Cancelled; session cleanup completed." );
			return 130;
		} catch ( Exception ) {
			await error.WriteLineAsync( "Clipboard operation failed; no payload is included in this diagnostic." );
			return 1;
		}
	}

	private static string Next( string[] args, ref int index ) {
		if ( ++index >= args.Length ) throw new ArgumentException( "Missing option value." );
		return args[ index ];
	}

	private static int Number( string value, int minimum ) {
		if ( !int.TryParse( value, NumberStyles.None, CultureInfo.InvariantCulture, out int number )
			|| number < minimum || number > TerminalClipboardOptions.SupportedMaximumBytes )
			throw new ArgumentException( "Byte count is outside the supported range." );
		return number;
	}
}
